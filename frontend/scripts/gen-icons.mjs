// Generates src/components/icon-paths.ts from design/assets/icons (run: node scripts/gen-icons.mjs)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = new URL("../../design/assets/icons/", import.meta.url).pathname;
const inner = (f) =>
  readFileSync(f, "utf8")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();
const icons = {};
for (const f of readdirSync(dir).filter((x) => x.endsWith(".svg") && !x.startsWith("_"))) icons[f.slice(0, -4)] = inner(join(dir, f));
const tab = {};
for (const f of readdirSync(join(dir, "mobile-tabbar")).filter((x) => x.endsWith(".svg")))
  tab[f.slice(0, -4)] = inner(join(dir, "mobile-tabbar", f));
const out =
  `// Generated by scripts/gen-icons.mjs from design/assets/icons — do not edit.\n` +
  `export const ICONS = ${JSON.stringify(icons, null, 1)} as const;\n` +
  `export const TAB_ICONS = ${JSON.stringify(tab, null, 1)} as const;\n` +
  `export type IconName = keyof typeof ICONS;\nexport type TabIconName = keyof typeof TAB_ICONS;\n`;
writeFileSync(new URL("../src/components/icon-paths.ts", import.meta.url), out);
console.log(Object.keys(icons).length, "icons,", Object.keys(tab).length, "tab icons");
